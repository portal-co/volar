// @pinnedness: unpinned
// @stability: very-unstable
//! @ai: generated
//! Element-file generation: mxx program → checked-in `volar-spec` source.
//!
//! Driven by `cargo xtask gen-specs`; freshness-gated by
//! `cargo xtask check-specs` like every other generated spec artifact.
//!
//! ## Phase-1 backend scoping
//!
//! Generated element files carry `//! @volar-codegen-exclude:`, keeping them
//! out of the parse-based TS/dyn/Lean-via-reparse outputs for now: the TS
//! printer's integer-width inference is not validated for the `u128`
//! intermediate arithmetic these modules use, and shipping silently
//! wrong-width TypeScript is worse than shipping none. Rust is the
//! validated backend (compile-and-run evidence per element). Lean coverage
//! arrives through Phase 2's dedicated transport (the lowered IR feeds
//! `printer_lean` directly, not via reparse); TS/dyn coverage follows once
//! their backends are validated for this arithmetic profile.

use crate::lower::{HelperMode, LowerOptions, lower_validated_to_module};
use crate::InteropError;
use crate::programs::ElementSpec;

/// The mxx revision all elements are generated from (kept in sync with the
/// `mxx-ir-core`/`mxx-dsl` git pins in this crate's `Cargo.toml`).
pub const MXX_PIN: &str = "11004eeb438aa13c57f3c5ec387b1eaa85bb2007";

fn banner(what: &str) -> String {
    format!(
        "//! @generated by `cargo xtask gen-specs` (volar-mxx-interop): {what},\n\
         //! from MachinaIO/mxx @ {MXX_PIN}. DO NOT EDIT; regenerate.\n\
         //! @volar-codegen-exclude: mxx-generated; TS/dyn/Lean-via-reparse backend\n\
         //! coverage lands with docs/mxx-cutover-plan.md Phase 2 (per-backend\n\
         //! semantics validation for the u128 arithmetic profile).\n\
         // @pinnedness: unpinned\n\
         // @stability: very-unstable\n\
         //! @ai: generated\n\n"
    )
}

/// The `volar-spec` `mxx_rt` module source: the interop crate's bundled
/// helpers with a generated banner, so there is exactly one source of truth
/// and `check-specs` fails on drift.
pub fn generate_rt_source() -> String {
    format!("{}{}", banner("ring arithmetic runtime helpers"), crate::rt::MXX_RT_SOURCE)
}

/// Generate one element's `volar-spec` source file.
pub fn generate_element_rust(element: &ElementSpec) -> Result<String, InteropError> {
    let (built, validated) = (element.build)()?;
    let module = lower_validated_to_module(
        &built.graph,
        &validated,
        &LowerOptions {
            function_name: element.function.to_string(),
            helpers: HelperMode::External {
                path: vec!["crate".to_string(), "mxx_rt".to_string()],
            },
            module_name: format!("mxx_{}", element.element),
        },
    )?;
    let body = crate::rt::print_standalone(&module);
    Ok(format!(
        "{}//! Element `{}`: mxx program `{}` lowered to spec Rust.\n\n{}",
        banner(&format!("spec element `{}`", element.element)),
        element.element,
        built.graph.name(),
        body
    ))
}
